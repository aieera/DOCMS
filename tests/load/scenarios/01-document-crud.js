// Scenario 1: Document CRUD — 1000 concurrent users, 500 creates/min,
// 5000 reads/min, sustained 30 minutes.
import http from 'k6/http';
import { check, sleep } from 'k6';
import { Counter, Trend } from 'k6/metrics';
import { BASE_URL, headers, randomTenant, randomString } from '../lib/config.js';

const docCreateDuration = new Trend('doc_create_duration', true);
const docReadDuration = new Trend('doc_read_duration', true);
const docUpdateDuration = new Trend('doc_update_duration', true);
const docDeleteDuration = new Trend('doc_delete_duration', true);
const docCreateCount = new Counter('doc_creates');
const docReadCount = new Counter('doc_reads');

export const options = {
  scenarios: {
    writers: {
      executor: 'constant-arrival-rate',
      rate: 500,
      timeUnit: '1m',
      duration: '30m',
      preAllocatedVUs: 200,
      maxVUs: 500,
    },
    readers: {
      executor: 'constant-arrival-rate',
      rate: 5000,
      timeUnit: '1m',
      duration: '30m',
      preAllocatedVUs: 800,
      maxVUs: 1200,
      exec: 'readDocuments',
    },
  },
  thresholds: {
    'doc_read_duration': ['p(99)<150'],
    'doc_create_duration': ['p(99)<500'],
    'http_req_failed': ['rate<0.01'],
  },
};

const createdDocIds = [];

export default function () {
  const tenantId = randomTenant();
  const h = headers(tenantId);

  // CREATE
  const createPayload = JSON.stringify({
    title: `Load Test Doc ${randomString(8)}`,
    workspace_id: `ws-${tenantId}`,
    lifecycle_state: 'draft',
    mime_type: 'application/pdf',
    description: 'Generated by k6 load test',
  });
  const createRes = http.post(`${BASE_URL}/documents`, createPayload, { headers: h });
  docCreateDuration.add(createRes.timings.duration);
  docCreateCount.add(1);
  check(createRes, { 'create 201': (r) => r.status === 201 });

  if (createRes.status === 201) {
    const doc = JSON.parse(createRes.body);
    createdDocIds.push({ id: doc.id, tenant: tenantId });

    // UPDATE
    const updateRes = http.patch(`${BASE_URL}/documents/${doc.id}`, JSON.stringify({
      description: `Updated at ${Date.now()}`,
    }), { headers: h });
    docUpdateDuration.add(updateRes.timings.duration);
    check(updateRes, { 'update 200': (r) => r.status === 200 });
  }

  sleep(0.1);
}

export function readDocuments() {
  const tenantId = randomTenant();
  const h = headers(tenantId);

  // LIST
  const listRes = http.get(`${BASE_URL}/documents?workspace_id=ws-${tenantId}&page_size=20`, { headers: h });
  docReadDuration.add(listRes.timings.duration);
  docReadCount.add(1);
  check(listRes, { 'list 200': (r) => r.status === 200 });

  // GET by ID (if we have any)
  if (createdDocIds.length > 0) {
    const pick = createdDocIds[Math.floor(Math.random() * createdDocIds.length)];
    const getRes = http.get(`${BASE_URL}/documents/${pick.id}`, { headers: headers(pick.tenant) });
    docReadDuration.add(getRes.timings.duration);
    check(getRes, { 'get 200': (r) => r.status === 200 || r.status === 404 });
  }

  sleep(0.05);
}
