#!/usr/bin/env node
// build-graphql-manifest.mjs — ADR 0074 persisted-query manifest builder.
//
// Reads every .graphql operation in web/.graphql/, canonicalizes the
// query text (collapses whitespace, trims), SHA-256s the result,
// and emits two artifacts:
//
//   web/.graphql/manifest.json        — runtime lookup for the urql
//                                        persisted-query exchange.
//   web/src/lib/graphql-operations.ts — typed string-literal exports
//                                        (DocumentDetailQuery,
//                                         ActivityForDocumentQuery, …)
//                                        so call sites get a hash
//                                        constant + variable types.
//
// And copies the same manifest.json to:
//   services/graphql-gateway/internal/persisted/manifest.json
//
// This guarantees the frontend hash and the backend allow-list are
// the same JSON file. CI fails the PR if they drift (compare via
// `git diff`).
//
// Run via:  npm run graphql:manifest

import { createHash } from 'node:crypto'
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const REPO_ROOT = resolve(__dirname, '../..')
const SOURCE_DIR = resolve(__dirname, '../.graphql')
const FRONTEND_OUT = join(SOURCE_DIR, 'manifest.json')
const TYPED_OUT = resolve(__dirname, '../src/lib/graphql-operations.ts')
const BACKEND_OUT = join(REPO_ROOT, 'services/graphql-gateway/internal/persisted/manifest.json')

// canonicalize collapses whitespace so superficial formatting (the
// difference between a pretty-printed query and its single-line form)
// doesn't change the hash. The backend's persisted.Hash() applies the
// same shape to its embedded entries — both sides hash the same bytes.
function canonicalize(src) {
  return src.replace(/\s+/g, ' ').trim()
}

function sha256Hex(s) {
  return createHash('sha256').update(s).digest('hex')
}

// extractOperationName pulls the GraphQL operation name from the
// canonicalized query for the typed-export filename.
function extractOperationName(doc) {
  const m = /^(?:query|mutation|subscription)\s+([A-Za-z_][A-Za-z0-9_]*)/.exec(doc)
  return m ? m[1] : null
}

const files = readdirSync(SOURCE_DIR)
  .filter((f) => f.endsWith('.graphql'))
  .sort() // deterministic output regardless of FS ordering

const manifest = {
  _comment:
    'ADR 0074 — generated by web/scripts/build-graphql-manifest.mjs. Do not hand-edit; regenerate via `npm run graphql:manifest`.',
}
const typedEntries = []

for (const file of files) {
  const raw = readFileSync(join(SOURCE_DIR, file), 'utf8')
  const doc = canonicalize(raw)
  const name = extractOperationName(doc)
  if (!name) {
    throw new Error(`could not extract operation name from ${file}`)
  }
  const hash = sha256Hex(doc)
  manifest[hash] = { name, doc }
  typedEntries.push({ name, hash, doc })
}

writeFileSync(FRONTEND_OUT, JSON.stringify(manifest, null, 2) + '\n')
writeFileSync(BACKEND_OUT, JSON.stringify(manifest, null, 2) + '\n')

const banner = `// Generated by web/scripts/build-graphql-manifest.mjs.
// Do not hand-edit. Regenerate via: npm run graphql:manifest
//
// Each export pairs the canonicalized query text with its SHA-256
// hash so the urql persisted exchange (web/src/lib/graphql.ts) can
// post { id: hash, variables } and the backend (ADR 0074) can resolve
// the query from its embedded allow-list.

export interface PersistedOperation {
  readonly name: string
  readonly hash: string
  readonly doc: string
}

`

const body = typedEntries
  .map(
    (e) =>
      `export const ${e.name}Query: PersistedOperation = {\n  name: ${JSON.stringify(e.name)},\n  hash: ${JSON.stringify(e.hash)},\n  doc: ${JSON.stringify(e.doc)},\n}\n`,
  )
  .join('\n')

writeFileSync(TYPED_OUT, banner + body)

console.log(
  `[graphql-manifest] wrote ${typedEntries.length} operation${typedEntries.length === 1 ? '' : 's'}:`,
)
for (const e of typedEntries) {
  console.log(`  - ${e.name}  ${e.hash.slice(0, 12)}…`)
}
console.log(`[graphql-manifest]   frontend: ${FRONTEND_OUT}`)
console.log(`[graphql-manifest]   backend:  ${BACKEND_OUT}`)
console.log(`[graphql-manifest]   typed:    ${TYPED_OUT}`)
