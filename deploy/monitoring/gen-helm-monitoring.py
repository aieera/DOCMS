#!/usr/bin/env python3
"""Generate the Helm monitoring templates from deploy/monitoring (O-1).

deploy/monitoring/alerts/*.yml and deploy/monitoring/alertmanager.yml stay
the single source of truth (compose mounts them directly). Helm can only
read files inside the chart, and every file under templates/ is parsed as
a Go template, so this script embeds each source verbatim in a Go-template
raw string (backticks: the {{ $labels.x }} / {{ .GroupLabels }} templates
inside pass through untouched) and writes:

  deploy/helm/sedoc/templates/monitoring/prometheusrule.yaml
  deploy/helm/sedoc/templates/monitoring/alertmanager-config-secret.yaml

Usage:
  python3 deploy/monitoring/gen-helm-monitoring.py          # write
  python3 deploy/monitoring/gen-helm-monitoring.py --check  # exit 1 if stale
"""
from __future__ import annotations

import argparse
import glob
import os
import sys

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", ".."))
OUT_DIR = os.path.join(REPO, "deploy", "helm", "sedoc", "templates", "monitoring")
HEADER = "{{- /* GENERATED by deploy/monitoring/gen-helm-monitoring.py from %s — do not edit. */ -}}\n"


def raw(text: str, src: str) -> str:
    if "`" in text:
        sys.exit(f"{src}: contains a backtick; it cannot be embedded in a Go raw string")
    return "`" + text + "`"


def indent(text: str, n: int) -> str:
    pad = " " * n
    return "".join(pad + line if line.strip() else line for line in text.splitlines(True))


def prometheus_rule() -> str:
    files = sorted(glob.glob(os.path.join(HERE, "alerts", "*.yml")))
    groups_text = []
    for f in files:
        doc = yaml.safe_load(open(f))
        if not doc or not doc.get("groups"):
            sys.exit(f"{f}: no groups")
        # Each file's own `groups:` list items, re-indented under spec.groups.
        text = open(f).read()
        body = text[text.index("groups:") + len("groups:"):].lstrip("\n")
        groups_text.append(f"# --- {os.path.relpath(f, REPO)} ---\n" + body.rstrip("\n") + "\n")
    joined = "".join(groups_text)
    yaml.safe_load("groups:\n" + joined)  # the concatenation must still parse
    srcs = ", ".join(os.path.relpath(f, REPO) for f in files)
    return (
        HEADER % srcs
        + "{{- $mon := include \"sedoc.monitoring.values\" . | fromYaml }}\n"
        + "{{- if and $mon.enabled $mon.prometheusRule.enabled }}\n"
        + "apiVersion: monitoring.coreos.com/v1\n"
        + "kind: PrometheusRule\n"
        + "metadata:\n"
        + "  name: {{ .Release.Name }}-alerts\n"
        + "  namespace: {{ .Release.Namespace }}\n"
        + "  labels:\n"
        + "    app.kubernetes.io/instance: {{ .Release.Name }}\n"
        + "    app.kubernetes.io/part-of: sedoc\n"
        + "    {{- with $mon.prometheusRule.labels }}\n"
        + "    {{- toYaml . | nindent 4 }}\n"
        + "    {{- end }}\n"
        + "spec:\n"
        + "  groups:\n"
        # kubernetes.yml scopes kube-state-metrics series to this release's
        # namespace through the __SEDOC_NAMESPACE__ token.
        + "{{ " + raw(indent(joined, 2), "alerts/*.yml") + " | replace \"__SEDOC_NAMESPACE__\" .Release.Namespace }}\n"
        + "{{- end }}\n"
    )


def alertmanager_secret() -> str:
    src = os.path.join(HERE, "alertmanager.yml")
    text = open(src).read()
    yaml.safe_load(text)
    if "${" in text:
        sys.exit(f"{src}: contains ${{...}}; Alertmanager does not expand env vars — use *_file")
    return (
        HEADER % os.path.relpath(src, REPO)
        + "{{- $mon := include \"sedoc.monitoring.values\" . | fromYaml }}\n"
        + "{{- $am := $mon.alertmanager }}\n"
        + "{{- if and $mon.enabled $am.configSecret.enabled }}\n"
        + "{{- $smtp := $am.smtp }}\n"
        + "{{- $cfg := " + raw(text, "alertmanager.yml") + " }}\n"
        + "{{- $cfg = replace \"__SMTP_SMARTHOST__\" (required \"monitoring.alertmanager.smtp.smarthost is required\" $smtp.smarthost) $cfg }}\n"
        + "{{- $cfg = replace \"__SMTP_FROM__\" (required \"monitoring.alertmanager.smtp.from is required\" $smtp.from) $cfg }}\n"
        + "{{- $cfg = replace \"__ALERT_DIGEST_TO__\" (required \"monitoring.alertmanager.smtp.digestTo is required\" $smtp.digestTo) $cfg }}\n"
        + "apiVersion: v1\n"
        + "kind: Secret\n"
        + "metadata:\n"
        + "  # Point the Alertmanager at it: kube-prometheus-stack\n"
        + "  # alertmanager.alertmanagerSpec.configSecret, and mount the receiver\n"
        + "  # credentials with alertmanagerSpec.secrets: [sedoc-alertmanager-receivers].\n"
        + "  name: {{ $am.configSecret.name }}\n"
        + "  namespace: {{ $am.namespace | default .Release.Namespace }}\n"
        + "  labels:\n"
        + "    app.kubernetes.io/instance: {{ .Release.Name }}\n"
        + "    app.kubernetes.io/part-of: sedoc\n"
        + "type: Opaque\n"
        + "data:\n"
        + "  alertmanager.yaml: {{ $cfg | b64enc }}\n"
        + "{{- end }}\n"
    )


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if the generated templates are stale")
    check = ap.parse_args().check
    outputs = {
        "prometheusrule.yaml": prometheus_rule(),
        "alertmanager-config-secret.yaml": alertmanager_secret(),
    }
    stale = []
    for name, content in outputs.items():
        path = os.path.join(OUT_DIR, name)
        current = open(path).read() if os.path.exists(path) else None
        if current == content:
            continue
        if check:
            stale.append(os.path.relpath(path, REPO))
        else:
            os.makedirs(OUT_DIR, exist_ok=True)
            with open(path, "w") as fh:
                fh.write(content)
            print("wrote", os.path.relpath(path, REPO))
    if stale:
        print("stale (run deploy/monitoring/gen-helm-monitoring.py):", ", ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
